// Disposable application_fixture.py only. No real model requests or user data.
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const base=process.env.CORKI_APPLICATION_TEST_URL;
if(!base?.startsWith('http://127.0.0.1:'))throw Error('Disposable fixture URL required');
const cli=(...args)=>execFileSync('agent-browser',['--session','corki-prompt-versions',...args],{encoding:'utf8'}).trim();
const ev=(code)=>JSON.parse(cli('eval',code));
const click=(selector)=>cli('click',selector);
const fill=(selector,text)=>{
  if(selector.includes('.cm-content')){
    cli('focus',selector);cli('press','Meta+a');cli('keyboard','inserttext',text);
  } else cli('fill',selector,text);
};
const wait=async(code)=>{for(let i=0;i<80;i++){if(ev(`Boolean(${code})`))return;await new Promise(r=>setTimeout(r,100));}throw Error('Timeout '+code);};
const tab=(value)=>click(`[data-app-tab=${value}]`);
const name='提示词版本验收-'+Date.now();
cli('open',base+'/#applications/new');
await wait('document.querySelector("[data-app-tab=info]")');
fill('[name=name]',name);
fill('[name=description]','初始描述');
tab('prompt');
fill('.application-prompt .cm-content','第一版：简洁回答。');
ev('(()=>{window.__retainedEditor=window.CorkiApplications.editor;return true;})()');
tab('info');
fill('[name=description]','切换标签时保留的描述');
tab('prompt');
assert(ev('window.__retainedEditor===window.CorkiApplications.editor'));
assert.equal(ev('window.CorkiApplications.form.description'),'切换标签时保留的描述');
assert.equal(ev('window.CorkiApplications.form.prompt'),'第一版：简洁回答。');
click('[data-app-action=save]');
await wait('document.querySelector("[data-app-action=edit]")');
const id=ev('window.CorkiApplications.id');
assert.equal(ev('document.querySelectorAll("[data-app-action=version]").length'),1);
assert.equal(ev('document.querySelector(".cm-content").contentEditable'),'false');
click('[data-app-action=edit]');
fill('.application-prompt .cm-content','第二版：先给结论，再解释原因。');
assert.equal(ev('document.querySelector("[data-app-action=save]").textContent'),'保存为新版本');
click('[data-app-action=save]');
await wait('document.querySelectorAll("[data-app-action=version]").length===2');
assert.equal(ev('window.CorkiApplications.app.version'),2);
assert.equal(ev('window.CorkiApplications.app.prompt'),'第二版：先给结论，再解释原因。');
// A basic-information save must not manufacture a duplicate prompt-history row.
tab('info');
click('[data-app-action=edit]');
fill('[name=description]','回滚后也应保留的最新描述');
click('[data-create-picker=provider] summary');
click('[data-create-pick=provider][data-value=local]');
click('[data-create-picker=model] summary');
click('[data-create-pick=model][data-value=test]');
click('[data-app-action=save]');
await wait('window.CorkiApplications.app.version===3');
tab('prompt');
assert.equal(ev('document.querySelectorAll("[data-app-action=version]").length'),2);
assert.equal(ev('document.querySelector("[data-app-action=version][aria-current=true]").dataset.version'),'2');
click('[data-app-action=version][data-version="1"]');
await wait('window.CorkiApplications.historical===1');
assert.equal(ev('window.CorkiApplications.form.prompt'),'第一版：简洁回答。');
tab('info');
assert.equal(ev('document.querySelector("[name=description]").value'),'回滚后也应保留的最新描述');
assert.equal(ev('window.CorkiApplications.form.provider'),'local');
tab('prompt');
click('[data-app-action=restore][data-version="1"]');
click('.application-confirm [data-confirm]');
await wait('window.CorkiApplications.app.version===4');
assert.equal(ev('window.CorkiApplications.app.prompt'),'第一版：简洁回答。');
assert.equal(ev('window.CorkiApplications.app.description'),'回滚后也应保留的最新描述');
assert.equal(ev('window.CorkiApplications.app.provider'),'local');
assert.equal(ev('window.CorkiApplications.app.model'),'test');
assert.equal(ev('document.querySelectorAll("[data-app-action=version]").length'),3);
for(const [width,height]of [[1280,800],[1440,900],[1920,1080]]){
 cli('set','viewport',String(width),String(height));
 assert(ev('document.documentElement.scrollWidth<=innerWidth'));
 cli('screenshot',`/tmp/corki-prompt-versions-${width}.png`);
}
// Keyboard tabs preserve the current editor and draft.
click('[data-app-action=edit]');
fill('.application-prompt .cm-content','尚未保存的第三版草稿');
ev('(()=>{window.__retainedEditor=window.CorkiApplications.editor;return true;})()');
cli('focus','[data-app-tab=prompt]');
cli('press','ArrowLeft');
assert.equal(ev('document.activeElement.dataset.appTab'),'info');
cli('press','ArrowRight');
assert(ev('window.__retainedEditor===window.CorkiApplications.editor'));
assert.equal(ev('window.CorkiApplications.form.prompt'),'尚未保存的第三版草稿');
assert(ev('[...document.querySelectorAll("[data-app-action=version]")].every(button=>button.disabled)'));
click('[data-app-action=cancel-edit]');
assert.equal(ev('window.CorkiApplications.form.prompt'),'第一版：简洁回答。');
click('[data-app-action=diff][data-version="2"]');
await wait('document.querySelector(".cm-mergeView")');
assert(ev('document.querySelector(".cm-mergeView").textContent.includes("第二版")'));
assert(!ev('document.querySelector(".cm-mergeView").textContent.includes("回滚后也应保留的最新描述")'));
click('[data-app-action=back-detail]');
await wait('document.querySelector("[data-app-tab=prompt][aria-selected=true]")');
assert.equal(cli('errors'),'');
await fetch(base+'/api/applications',{method:'POST',headers:{'Content-Type':'application/json','X-Corki-Manager':'1'},body:JSON.stringify({action:'delete',app:id,stop:true})});
console.log('PASS: stable tabs and drafts, prompt revisions, no duplicate info-only revisions, readonly history, prompt-only rollback preserving current settings, keyboard tabs, cancel, prompt-only Diff and3desktop sizes.');
