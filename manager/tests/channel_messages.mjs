// Run only against an isolated manager with a fake proactive-send boundary.
import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import path from 'node:path';
import os from 'node:os';
const base=process.env.MANAGER_TEST_URL;assert(base);
const config=await(await fetch(base+'/api/config')).json();
assert(config.path.includes('corki-channel-message-qa-'));
const run=promisify(execFile),session='channel-messages-'+process.pid;
const browser=(...args)=>run('agent-browser',['--session',session,...args],{maxBuffer:1024*1024});
const value=async code=>JSON.parse((await browser('eval',code)).stdout.trim());
const wait=async code=>{for(let i=0;i<80;i++){if(await value(`Boolean(${code})`))return;await new Promise(r=>setTimeout(r,100));}throw Error(code);};
const click=async selector=>{await browser('click',selector);};
try{
 await browser('open',base+'/#channels');await browser('set','viewport','1440','1000');
 await wait(`document.querySelector('[data-config]')`);await click('[data-config]');
 await wait(`document.querySelector('[data-channel-tab="history"]')`);await click('[data-channel-tab="history"]');
 await wait(`document.querySelectorAll('[data-session]').length===2`);
 const peers=await value(`[...document.querySelectorAll('[data-session]')].map(b=>({name:b.textContent.trim(),id:b.dataset.session}))`);
 const alice=peers.find(p=>p.name==='Alice').id,bob=peers.find(p=>p.name==='Bob').id;
 const select=async id=>{await wait(`document.querySelector('[data-session="${id}"]')`);await click(`[data-session="${id}"]`);await wait(`document.querySelector('.channel-message-composer textarea').disabled===false`);};
 await select(alice);
 const sentText='Fixture manual hello '+process.pid;
 const input='.channel-message-composer textarea',send='.channel-message-composer button[type="submit"]';
 await browser('fill',input,sentText);
 await value(`document.querySelector(${JSON.stringify(input)}).dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',isComposing:true,bubbles:true}));true`);
 assert.equal(await value(`document.querySelector(${JSON.stringify(input)}).value`),sentText);
 await select(bob);assert.equal(await value(`document.querySelector(${JSON.stringify(input)}).value`),'');
 await browser('fill',input,'Bob draft');await select(alice);
 assert.equal(await value(`document.querySelector(${JSON.stringify(input)}).value`),sentText);
 await click(send);await click(`[data-session="${bob}"]`);
 await wait(`document.querySelector('.channel-message-composer textarea').disabled===false`);
 assert.equal(await value(`document.querySelector(${JSON.stringify(input)}).value`),'Bob draft');
 await select(alice);
 await wait(`[...document.querySelectorAll('.channel-chat-text')].some(n=>n.textContent.trim()===${JSON.stringify(sentText)})`);
 await wait(`document.querySelector(${JSON.stringify(input)}).value===''`);
 assert.equal(await value(`[...document.querySelectorAll('.channel-chat-text')].filter(n=>n.textContent.trim()===${JSON.stringify(sentText)}).length`),1);
 await browser('fill',input,'fixture failure');await click(send);
 await wait(`document.querySelector('.channel-reply-failed:not([hidden])')`);
 await click('.channel-reply-failed:not([hidden])');
 assert((await value(`document.querySelector('.channel-dialog-body').textContent`)).includes('HTTP 403'));
 await click('.channel-dialog-foot [data-close]');
 await click('[data-fold-contacts]');
 assert.equal(await value(`document.querySelector('[data-fold-contacts]').getAttribute('aria-expanded')`),'false');
 assert.equal(await value(`getComputedStyle(document.querySelector('.channel-session-list')).display`),'none');
 await browser('reload');await wait(`document.querySelector('[data-fold-contacts]')`);
 assert.equal(await value(`document.querySelector('[data-fold-contacts]').getAttribute('aria-expanded')`),'false');
 await click('[data-fold-contacts]');await select(alice);
 await browser('screenshot',path.join(os.tmpdir(),'corki-channel-messages.png'));
 console.log('PASS manual send, notices, per-contact drafts, IME, switching, failure details, collapse and reload');
}finally{await browser('close').catch(()=>{});}
